/*
 * Browser Lag Fix — settings model shared by the service worker, popup and options page.
 * Pure module (no chrome.* calls) so it can be unit tested in Node.
 */

/** Cap values offered in the UI; each has a pre-generated boot-config file. */
export const CAP_CHOICES_GIB = [1, 2, 5, 10, 20, 50, 100];

export const DEFAULTS = Object.freeze({
  enabled: true,
  mode: 'block',        // 'block' | 'log'
  capGiB: 10,            // matches the quota Chromium reports via navigator.storage.estimate()
  diagnostics: false,    // capture JS call stacks for blocked calls
  allowlist: [],         // hostnames, e.g. ["photopea.com", "app.example.org"]
});

const HOST_RE = /^(?=.{1,253}$)(?!-)[a-z0-9-]{1,63}(?<!-)(\.(?!-)[a-z0-9-]{1,63}(?<!-))*$/;

/** Lower-cases, strips scheme/path/port and wildcard prefix; returns '' if not a hostname. */
export function normalizeHost(input) {
  let h = String(input || '').trim().toLowerCase();
  h = h.replace(/^[a-z][a-z0-9+.-]*:\/\//, '').replace(/[/?#].*$/, '').replace(/:\d+$/, '').replace(/^\*\./, '').replace(/\.$/, '');
  return HOST_RE.test(h) ? h : '';
}

export function normalizeSettings(raw) {
  const s = { ...DEFAULTS, ...(raw || {}) };
  return {
    enabled: s.enabled !== false,
    mode: s.mode === 'log' ? 'log' : 'block',
    capGiB: CAP_CHOICES_GIB.includes(Number(s.capGiB)) ? Number(s.capGiB) : DEFAULTS.capGiB,
    diagnostics: !!s.diagnostics,
    allowlist: [...new Set((Array.isArray(s.allowlist) ? s.allowlist : []).map(normalizeHost).filter(Boolean))].sort(),
  };
}

/** Each allow-listed host covers itself and its subdomains, over http and https. */
export function toMatchPatterns(allowlist) {
  return allowlist.flatMap(h => [`*://${h}/*`, `*://*.${h}/*`]);
}

/** Path (relative to the extension root) of the boot-config script for these settings. */
export function bootConfigFile(s) {
  return `src/boot/cap-${s.capGiB}-${s.mode}${s.diagnostics ? '-diag' : ''}.js`;
}

/** Contents of a boot-config script; used by the generator and verified by tests. */
export function bootConfigSource(capGiB, mode, diagnostics) {
  const capBytes = capGiB * 1024 ** 3;
  return `// Generated by tools/gen-boot-configs.mjs — do not edit.\n` +
    `globalThis.__lagFixBootConfig__ = Object.freeze({ mode: '${mode}', capBytes: ${capBytes}, diagnostics: ${diagnostics} });\n`;
}

export function allBootConfigs() {
  const out = [];
  for (const capGiB of CAP_CHOICES_GIB) {
    for (const mode of ['block', 'log']) {
      for (const diagnostics of [false, true]) {
        out.push({ file: bootConfigFile({ capGiB, mode, diagnostics }), source: bootConfigSource(capGiB, mode, diagnostics) });
      }
    }
  }
  return out;
}
